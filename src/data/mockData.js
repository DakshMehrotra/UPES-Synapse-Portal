// AI Matchmaker score calculator
export function calculateMentorMatchScore(abstractText, mentor) {
  if (!abstractText || abstractText.trim().length === 0) return 65; // Base default
  
  const text = abstractText.toLowerCase();
  let score = 55; // start baseline
  
  const domainKeywords = {
    'ai': ['ai', 'machine learning', 'deep learning', 'nlp', 'model', 'neural', 'predictive', 'llm', 'autonomous'],
    'cloud': ['cloud', 'aws', 'docker', 'kubernetes', 'microservices', 'distributed', 'edge', 'serverless'],
    'security': ['security', 'cyber', 'cryptography', 'zero trust', 'network', 'blockchain', 'auth'],
    'web': ['web', 'react', 'full stack', 'frontend', 'ui/ux', 'portal', 'javascript', 'node'],
    'blockchain': ['blockchain', 'solidity', 'smart contract', 'web3', 'ethereum', 'rust']
  };

  mentor.researchAreas.forEach((area) => {
    const areaLower = area.toLowerCase();
    // Direct string match in abstract
    if (text.includes(areaLower)) {
      score += 20;
    }
    // Keyword similarity check
    Object.keys(domainKeywords).forEach((key) => {
      if (areaLower.includes(key)) {
        domainKeywords[key].forEach((kw) => {
          if (text.includes(kw)) {
            score += 8;
          }
        });
      }
    });
  });

  // Cap score between 40 and 99
  return Math.min(99, Math.max(40, score));
}
